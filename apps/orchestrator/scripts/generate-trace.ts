/**
 * Generates a deterministic example collaboration trace by running the
 * research workflow with an injected clock and uuid sequence, then writing
 * it to examples/research-collaboration-trace.json.
 *
 * Usage: pnpm --filter @sentinel-mesh/orchestrator-service run generate:trace
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { InMemoryEventBus } from "@sentinel-mesh/queue";
import { PassThrough } from "node:stream";
import {
  OrchestrationEngine,
  InMemoryTaskStore,
  InMemoryRunStore,
  InMemoryEventOutbox,
  InMemoryProcessedEvents,
} from "@sentinel-mesh/orchestrator";
import { createLogger } from "@sentinel-mesh/logger";
import { registerResearchAgents, researchWorkflowPlan } from "@sentinel-mesh/agents";

const BASE_TIME = Date.parse("2026-01-05T12:00:00.000Z");
let clockMs = BASE_TIME;
let counter = 0;

/** Deterministic uuid v4-shaped ids so the committed example is stable. */
function seqUuid(): string {
  counter += 1;
  return `00000000-0000-4000-8000-${String(counter).padStart(12, "0")}`;
}

async function main(): Promise<void> {
  const sink = new PassThrough();
  sink.resume();
  const logger = createLogger({ service: "trace-gen", level: "silent", destination: sink });

  const bus = new InMemoryEventBus();
  const engine = new OrchestrationEngine({
    bus,
    taskStore: new InMemoryTaskStore(),
    runStore: new InMemoryRunStore(),
    outbox: new InMemoryEventOutbox(),
    processedEvents: new InMemoryProcessedEvents(),
    clock: { now: () => new Date(clockMs += 1) },
    logger,
    uuid: seqUuid,
  });
  registerResearchAgents(engine);

  const { run, traceId } = await engine.startWorkflow(
    researchWorkflowPlan({ topic: "base ecosystem", maxDocuments: 3 }),
  );
  await engine.settle();
  const finalRun = await engine.getRun(run.runId);
  const tasks = await engine.listTasks();
  const trace = engine.getTrace(traceId);

  const document = {
    title: "Sentinel Mesh example collaboration trace",
    description:
      "Deterministic end-to-end trace of the research collaboration workflow: research-agent -> source-verification-agent -> news-intelligence-agent. Generated by apps/orchestrator/scripts/generate-trace.ts with an injected clock and uuid sequence, so it is byte-stable across runs.",
    generatedAt: new Date(BASE_TIME).toISOString(),
    workflow: finalRun,
    tasks: tasks.map((record) => ({
      taskId: record.task.taskId,
      agentId: record.task.agentId ?? record.task.assignedAgentId,
      taskType: record.task.taskType,
      status: record.status,
      attempt: record.task.attempt,
      traceId: record.task.traceId,
      result: record.result ?? null,
    })),
    trace: {
      traceId,
      events: trace.map((envelope) => ({
        type: envelope.type,
        eventId: envelope.eventId,
        occurredAt: envelope.occurredAt,
        actor: envelope.actor,
        correlationId: envelope.correlationId,
        payloadSummary: summarizePayload(envelope.payload),
      })),
    },
  };

  const here = dirname(fileURLToPath(import.meta.url));
  const outPath = join(here, "..", "..", "..", "examples", "research-collaboration-trace.json");
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, `${JSON.stringify(document, null, 2)}\n`, "utf8");
  console.error(`trace written to ${outPath}: ${trace.length} events, run status ${finalRun?.status}`);
}

type PayloadSummary = Record<string, unknown>;
function summarizePayload(payload: unknown): PayloadSummary {
  if (typeof payload !== "object" || payload === null) {
    return { payload };
  }
  const record = payload as Record<string, unknown>;
  if (record["taskType"] !== undefined) {
    return { taskId: record["taskId"], taskType: record["taskType"], attempt: record["attempt"] };
  }
  if (record["status"] !== undefined && record["taskId"] !== undefined) {
    return { taskId: record["taskId"], status: record["status"], attempt: record["attempt"] };
  }
  if (record["from"] !== undefined && record["to"] !== undefined) {
    return { runId: record["runId"], from: record["from"], to: record["to"], reason: record["reason"] };
  }
  return { keys: Object.keys(record) };
}

main().catch((error: unknown) => {
  console.error(`trace generation failed: ${String(error)}`);
  process.exit(1);
});
